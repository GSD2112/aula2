var num1 = 5
var num2 = 15
var op = "/" 

if (op == "+"){
    console.log ("a soma dos numeros é " + (num1 + num2))
}
if (op == "-"){
    console.log ("a subtração dos numeros é " + (num1 - num2))
}
if (op == "*"){
    console.log ("a multiplicação dos numeros é " + (num1 * num2))
}
if (op == "/"){
    console.log ("a divisão dos numeros é " + (num1 / num2))
}